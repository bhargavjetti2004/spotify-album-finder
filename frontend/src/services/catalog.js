export function compareFallback(id1, id2) {
  const a1 = FALLBACK_ALBUMS.find((a) => a.id === id1) || FALLBACK_ALBUMS[0];
  const a2 = FALLBACK_ALBUMS.find((a) => a.id === id2) || FALLBACK_ALBUMS[1];

  const score1 = Math.round((a1.popularity / 100) * 60 + (Math.min(a1.totalTracks, 20) / 20) * 25 + 14);
  const score2 = Math.round((a2.popularity / 100) * 60 + (Math.min(a2.totalTracks, 20) / 20) * 25 + 14);

  let winner = "Tie";
  let winnerAlbumName = "Both albums scored equally";
  if (score1 > score2) {
    winner = "Album 1";
    winnerAlbumName = a1.name;
  } else if (score2 > score1) {
    winner = "Album 2";
    winnerAlbumName = a2.name;
  }

  return {
    album1: a1,
    album2: a2,
    album1Score: score1,
    album2Score: score2,
    winner,
    winnerAlbumName,
    explanation: `Project Comparison Score: ${a1.name} scored ${score1} pts vs ${a2.name} (${score2} pts).`
  };
}
